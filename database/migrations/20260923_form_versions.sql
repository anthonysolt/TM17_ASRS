BEGIN;

CREATE TABLE IF NOT EXISTS form_version (
  form_version_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_id INTEGER NOT NULL REFERENCES form(form_id) ON DELETE CASCADE,
  version_number INTEGER NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('draft', 'published', 'retired')),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  published_at TEXT,
  created_by_user_id INTEGER REFERENCES "user"(user_id),
  UNIQUE (form_id, version_number)
);

INSERT INTO form_version (form_id, version_number, status, created_at, published_at)
SELECT form_id, 1,
       CASE WHEN is_published = 1 THEN 'published' ELSE 'draft' END,
       COALESCE(created_at, CURRENT_TIMESTAMP::text),
       CASE WHEN is_published = 1 THEN COALESCE(updated_at, created_at, CURRENT_TIMESTAMP::text) ELSE NULL END
FROM form
WHERE NOT EXISTS (
  SELECT 1 FROM form_version fv WHERE fv.form_id = form.form_id
);

ALTER TABLE form_questions ADD COLUMN IF NOT EXISTS form_version_id INTEGER;

UPDATE form_questions fq
SET form_version_id = fv.form_version_id
FROM form_version fv
WHERE fv.form_id = fq.form_id
  AND fv.version_number = 1
  AND fq.form_version_id IS NULL;

ALTER TABLE form_questions
  ALTER COLUMN form_version_id SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'form_questions_form_version_fk'
  ) THEN
    ALTER TABLE form_questions
      ADD CONSTRAINT form_questions_form_version_fk
      FOREIGN KEY (form_version_id) REFERENCES form_version(form_version_id) ON DELETE CASCADE;
  END IF;

  IF EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'form_questions_form_id_field_id_key'
  ) THEN
    ALTER TABLE form_questions DROP CONSTRAINT form_questions_form_id_field_id_key;
  END IF;
END $$;

-- Older databases enforce the same per-form uniqueness through this index name.
DROP INDEX IF EXISTS idx_form_field_unique;

CREATE UNIQUE INDEX IF NOT EXISTS form_questions_version_field_key
  ON form_questions(form_version_id, field_id);
CREATE INDEX IF NOT EXISTS idx_form_version_form_status
  ON form_version(form_id, status, version_number DESC);

ALTER TABLE submission ADD COLUMN IF NOT EXISTS form_version_id INTEGER;

UPDATE submission s
SET form_version_id = fv.form_version_id
FROM form_version fv
WHERE fv.form_id = s.form_id
  AND fv.version_number = 1
  AND s.form_version_id IS NULL;

ALTER TABLE submission
  ALTER COLUMN form_version_id SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'submission_form_version_fk'
  ) THEN
    ALTER TABLE submission
      ADD CONSTRAINT submission_form_version_fk
      FOREIGN KEY (form_version_id) REFERENCES form_version(form_version_id);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_submission_form_version
  ON submission(form_version_id);
CREATE UNIQUE INDEX IF NOT EXISTS one_published_version_per_form
  ON form_version(form_id) WHERE status = 'published';

COMMIT;
